  constraint venues_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint venues_description_length check (char_length(description) between 30 and 2000),
  constraint venues_phone_format check (phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  constraint venues_whatsapp_format check (whatsapp_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  constraint venues_address_length check (char_length(address) between 5 and 240),
  constraint venues_zone_length check (char_length(zone) between 2 and 100),
  constraint venues_city_length check (char_length(city) between 2 and 100),
  constraint venues_latitude_range check (latitude between -90 and 90),
  constraint venues_longitude_range check (longitude between -180 and 180),
  constraint venues_review_note_length check (review_note is null or char_length(review_note) between 5 and 1000)
