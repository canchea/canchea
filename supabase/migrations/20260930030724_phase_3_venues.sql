create function public.register_my_venue_photo(
  p_object_path text,
  p_kind public.venue_photo_kind,
  p_alt_text text
)
returns public.venue_photos
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_venue public.venues;
  v_photo public.venue_photos;
begin
  select * into v_venue
  from public.venues
  where owner_id = v_user_id;

  if v_user_id is null or not found or v_venue.status not in ('draft', 'rejected', 'changes_requested') then
    raise exception 'Editable venue required' using errcode = '42501';
  end if;

  if p_object_path is null
     or split_part(p_object_path, '/', 1) <> v_venue.id::text
     or p_object_path ~ '(^|/)\.\.?(/|$)'
     or char_length(trim(coalesce(p_alt_text, ''))) not between 3 and 160 then
    raise exception 'Invalid photo data' using errcode = '22023';
  end if;

  if p_kind = 'gallery' and (
    select count(*) from public.venue_photos where venue_id = v_venue.id and kind = 'gallery'
  ) >= 10 then
    raise exception 'Gallery limit reached' using errcode = '22023';
  end if;

  insert into public.venue_photos (venue_id, object_path, kind, alt_text, created_by)
  values (v_venue.id, p_object_path, p_kind, trim(p_alt_text), v_user_id)
  returning * into v_photo;

  return v_photo;
end;
$$;

revoke execute on function public.register_my_venue_photo(text, public.venue_photo_kind, text) from public, anon;
grant execute on function public.register_my_venue_photo(text, public.venue_photo_kind, text) to authenticated;

create function public.delete_my_venue_photo(p_photo_id uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_object_path text;
begin
  delete from public.venue_photos p
  using public.venues v
  where p.id = p_photo_id
    and p.venue_id = v.id
    and v.owner_id = v_user_id
    and v.status in ('draft', 'rejected', 'changes_requested')
  returning p.object_path into v_object_path;

  if v_object_path is null then
    raise exception 'Editable photo not found' using errcode = '42501';
  end if;

  return v_object_path;
end;
$$;

