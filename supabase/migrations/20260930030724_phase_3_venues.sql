create function public.submit_my_venue(p_venue_id uuid)
returns public.venues
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_venue public.venues;
  v_previous_status public.venue_status;
begin
  select * into v_venue
  from public.venues
  where id = p_venue_id and owner_id = v_user_id
  for update;

  if not found or v_venue.status not in ('draft', 'rejected', 'changes_requested') then
    raise exception 'Editable venue not found' using errcode = '42501';
  end if;

  if not exists (select 1 from public.venue_services where venue_id = v_venue.id)
     or not exists (select 1 from public.venue_opening_hours where venue_id = v_venue.id and not is_closed)
     or not exists (select 1 from public.venue_photos where venue_id = v_venue.id and kind = 'logo')
     or not exists (select 1 from public.venue_photos where venue_id = v_venue.id and kind = 'cover') then
    raise exception 'Venue needs services, opening hours, logo and cover' using errcode = '22023';
  end if;

  v_previous_status := v_venue.status;

  update public.venues
  set status = 'pending_approval',
      submitted_at = timezone('utc', now()),
      review_note = null,
      reviewed_at = null,
      reviewed_by = null
  where id = v_venue.id
  returning * into v_venue;

  insert into public.venue_status_history (venue_id, from_status, to_status, changed_by)
  values (v_venue.id, v_previous_status, 'pending_approval', v_user_id);

  return v_venue;
end;
$$;

revoke execute on function public.submit_my_venue(uuid) from public, anon;
grant execute on function public.submit_my_venue(uuid) to authenticated;

create function public.review_venue(
  p_venue_id uuid,
  p_decision text,
  p_note text default null
)
returns public.venues
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_venue public.venues;
  v_new_status public.venue_status;
  v_clean_note text := nullif(trim(coalesce(p_note, '')), '');
begin
  if v_user_id is null or (select private.current_user_role()) <> 'super_admin' then
    raise exception 'Super admin role required' using errcode = '42501';
  end if;

  select * into v_venue
  from public.venues
  where id = p_venue_id
  for update;

  if not found or v_venue.status <> 'pending_approval' then
    raise exception 'Pending venue not found' using errcode = '22023';
  end if;

  v_new_status := case p_decision
    when 'approve' then 'approved'::public.venue_status
    when 'reject' then 'rejected'::public.venue_status
    when 'request_changes' then 'changes_requested'::public.venue_status
    else null
  end;

  if v_new_status is null then
    raise exception 'Invalid review decision' using errcode = '22023';
  end if;

  if v_new_status <> 'approved' and char_length(coalesce(v_clean_note, '')) not between 5 and 1000 then
    raise exception 'A review note is required' using errcode = '22023';
  end if;

  update public.venues
  set status = v_new_status,
      review_note = v_clean_note,
      reviewed_at = timezone('utc', now()),
      reviewed_by = v_user_id,
      approved_at = case when v_new_status = 'approved' then timezone('utc', now()) else approved_at end
  where id = v_venue.id
  returning * into v_venue;

  insert into public.venue_status_history (venue_id, from_status, to_status, note, changed_by)
  values (v_venue.id, 'pending_approval', v_new_status, v_clean_note, v_user_id);

  return v_venue;
end;
$$;

revoke execute on function public.review_venue(uuid, text, text) from public, anon;
grant execute on function public.review_venue(uuid, text, text) to authenticated;

